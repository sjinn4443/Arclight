// Keep the shared router small: lesson copy is loaded only by the Ears UI.
import fs from "node:fs";
import { EAR_TOPICS } from "../public/js/earsContentData.js";

const topics = Object.fromEntries(
  Object.entries(EAR_TOPICS).map(([id, topic]) => [
    id,
    topic.groups.flatMap((group) => group.lessons),
  ]),
);
const output = `// Generated by scripts/generate-ears-route-index.mjs.\nconst topics = ${JSON.stringify(topics, null, 2)};\nexport const EAR_ROUTE_PARENTS = Object.freeze({\n  ...Object.fromEntries(Object.keys(topics).map(id => [id, "ears"])),\n  ...Object.fromEntries(Object.entries(topics).flatMap(([parent, lessons]) => lessons.map(id => [id, parent]))),\n});\nexport const EAR_ROUTES = Object.freeze(Object.keys(EAR_ROUTE_PARENTS));\n`;
fs.writeFileSync(
  new URL("../public/js/earsRoutes.js", import.meta.url),
  output,
);
