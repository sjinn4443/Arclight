// Derive CSS clipping contours from the original artwork; source pixels stay intact.
const fs = require("node:fs/promises");
const path = require("node:path");
const sharp = require("sharp");

const cross = (o, a, b) =>
  (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
function hull(points) {
  points.sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const half = (sequence) => {
    const result = [];
    for (const point of sequence) {
      while (
        result.length > 1 &&
        cross(result.at(-2), result.at(-1), point) <= 0
      )
        result.pop();
      result.push(point);
    }
    return result.slice(0, -1);
  };
  return [...half(points), ...half([...points].reverse())];
}

async function main() {
  const source = path.resolve(__dirname, "../public/images/atoms");
  const outlines = {};
  for (const filename of (await fs.readdir(source))
    .filter((f) => f.endsWith(".webp"))
    .sort()) {
    const { data, info } = await sharp(path.join(source, filename))
      .removeAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    const points = [];
    for (let y = 0; y < info.height; y++) {
      let left = info.width,
        right = -1;
      for (let x = 0; x < info.width; x++) {
        const index = (y * info.width + x) * info.channels;
        if (
          data[index] < 245 ||
          data[index + 1] < 245 ||
          data[index + 2] < 245
        ) {
          left = Math.min(left, x);
          right = x;
        }
      }
      if (right >= left) points.push([left, y], [right + 1, y]);
    }
    if (points.length < 3) continue;
    const polygon = hull(points);
    // A small outward allowance keeps antialiased border pixels on the image.
    const cx = info.width / 2,
      cy = info.height / 2;
    const clip =
      "polygon(" +
      polygon
        .map(([x, y]) => {
          const dx = x - cx,
            dy = y - cy,
            length = Math.hypot(dx, dy) || 1;
          return `${(((x + (dx / length) * 0.6) / info.width) * 100).toFixed(3)}% ${(((y + (dy / length) * 0.6) / info.height) * 100).toFixed(3)}%`;
        })
        .join(",") +
      ")";
    outlines[filename] = clip;
  }
  const output = path.resolve(__dirname, "../public/js/atomsCardOutlines.js");
  await fs.writeFile(
    output,
    "// Generated by scripts/build-atoms-card-outlines.cjs from original image contours.\nexport const ATOMS_CARD_OUTLINES = " +
      JSON.stringify(outlines, null, 2) +
      ";\n",
  );
  console.log(
    `Derived ${Object.keys(outlines).length} original card contours.`,
  );
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
