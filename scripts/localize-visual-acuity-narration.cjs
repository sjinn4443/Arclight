const fs = require("node:fs");
const path = require("node:path");
const translations = require("./visual-acuity-translations.json");
const root = path.resolve(__dirname, "..");
const read = (file) =>
  JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));
const write = (file, data) =>
  fs.writeFileSync(path.join(root, file), JSON.stringify(data, null, 2) + "\n");
const base = "/narration/visual-acuity/full-animation/";
const scriptPath = `public${base}script.json`;
const script = read(scriptPath);
const voices = read(
  "public/narration/fundal-reflex/full-animation/script.json",
).languages;
for (const [language, lines] of Object.entries(translations)) {
  if (lines.length !== script.cues.length || lines.some((line) => !line.trim()))
    throw new Error(`Missing ${language} cues`);
  script.languages[language] = voices[language];
  script.cues.forEach((cue, index) => {
    cue[language] = lines[index];
  });
}
