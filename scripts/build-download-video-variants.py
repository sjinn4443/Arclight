"""Build missing low MP4s without changing originals; emit the shared quality map.

Run with Python and --ffmpeg <binary>. Existing 220p/240p exports are reused.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--ffmpeg', required=True)
args = parser.parse_args()
videos = ROOT / 'public/videos'
files = sorted(p for p in videos.rglob('*.mp4') if 'New folder' not in p.parts)
files += sorted((ROOT / 'public/images/pdf').rglob('*.mp4'))
pairs = []
by_digest = {}
intro_aliases = []
report = []
url = lambda p: '/' + p.relative_to(ROOT / 'public').as_posix()
for source in files:
    if source.name == 'MobilePhoneAttachment_720p.mp4':
        continue  # Existing PhoneAttach.mp4 is its 240p H.264 counterpart.
    if source.parent == videos / 'Core/Intro' and source.name.endswith('_720p.mp4'):
        # Byte-identical high source also lives in the Childhood directory.
        existing_low = videos / 'USAID Childhood eye screening' / source.name.replace('_720p', '_220p')
        existing_high = existing_low.with_name(existing_low.name.replace('_220p', '_720p'))
        if existing_low.exists() and existing_high.exists() and hashlib.sha256(source.read_bytes()).digest() == hashlib.sha256(existing_high.read_bytes()).digest():
            intro_aliases.append(url(source))
            continue
    if re.search(r'_(220|240)p$', source.stem, re.I):
        continue
    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if digest in by_digest:
        by_digest[digest].setdefault('aliases', []).append(url(source))
        continue
    stem = re.sub(r'_(540|720|1080)p$', '', source.stem, flags=re.I)
    low = next((source.with_name(stem + suffix) for suffix in ('_220p.mp4', '_240p.mp4')
                if source.with_name(stem + suffix).exists()), None)
    if low is None:
        probe = subprocess.run([args.ffmpeg, '-hide_banner', '-i', str(source)],
                               capture_output=True, text=True, errors='replace')
        dimensions = re.search(r'Video:.*?\b(\d{2,5})x(\d{2,5})\b', probe.stderr)
        if not dimensions:
            raise RuntimeError('Cannot inspect ' + str(source))
        if int(dimensions[2]) <= 360:
            continue
        low = source.with_name(stem + '_240p.mp4')
        temporary = low.with_suffix('.encoding.mp4')
        subprocess.run([args.ffmpeg, '-hide_banner', '-loglevel', 'error', '-y',
                        '-i', str(source), '-map', '0:v:0', '-map', '0:a:0?',
                        '-vf', 'scale=-2:240,setsar=1', '-c:v', 'libx264',
                        '-preset', 'fast', '-crf', '28', '-pix_fmt', 'yuv420p',
                        '-c:a', 'aac', '-b:a', '48k', '-movflags', '+faststart',
                        str(temporary)], check=True)
        temporary.replace(low)
        report.append({'high': url(source), 'low': url(low),
                       'highBytes': source.stat().st_size, 'lowBytes': low.stat().st_size})
        print('Created ' + url(low), flush=True)
    pair = {'low': url(low), 'high': url(source)}
    pairs.append(pair)
    by_digest[digest] = pair

# These legacy player URLs describe the same lessons under different names.
phone = {'low': '/videos/Arclight/PhoneAttach.mp4',
         'high': '/videos/Tools/MobilePhoneAttachment_720p.mp4'}
pairs = [p for p in pairs if p['high'] != phone['high']]
pairs.append(phone)
for pair in pairs:
    if pair['high'].startswith('/videos/USAID Childhood eye screening/1. How to use the Arclight'):
        pair.setdefault('aliases', []).extend(intro_aliases)
data = json.dumps(pairs, ensure_ascii=True, indent=2)
runtime = '''
  const path = (url) => {
    try { return decodeURIComponent(new URL(url, "https://arclight.invalid").pathname).toLowerCase(); }
    catch { return ""; }
  };
  const index = new Map();
  for (const pair of pairs) for (const url of [pair.low, pair.high, ...(pair.aliases || [])]) index.set(path(url), pair);
  globalThis.ArclightVideoQuality = {
    pairs,
    pair: (url) => index.get(path(url)),
    resolve: (url, quality) => index.get(path(url))?.[quality] || url,
  };
})();
'''
target = ROOT / 'public/video-localization/video-quality.js'
target.write_text('// Generated by scripts/build-download-video-variants.py\n(() => {\n  const pairs = ' + data + ';\n' + runtime, encoding='utf-8')
out = ROOT / '.codex-artifacts/download-optimization'
out.mkdir(parents=True, exist_ok=True)
(out / 'encoded.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
print(f'Registered {len(pairs)} quality pairs; created {len(report)} low exports.', flush=True)
